DO $$
BEGIN
IF to_regclass('public.users') IS NULL THEN RETURN; END IF;
CREATE TABLE IF NOT EXISTS carbon_assessments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id), inputs_json text NOT NULL,
    result_json text NOT NULL, created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS waste_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id), action_key varchar(80) NOT NULL,
    material varchar(30) NOT NULL, mass_kg double precision NOT NULL,
    baseline varchar(20) NOT NULL, selected varchar(20) NOT NULL,
    estimated_difference_kg double precision, evidence varchar(30) NOT NULL,
    factor_version varchar(50) NOT NULL, created_at timestamptz NOT NULL,
    UNIQUE(user_id, action_key)
);
CREATE INDEX IF NOT EXISTS idx_waste_actions_user ON waste_actions(user_id, created_at);
END
$$;
