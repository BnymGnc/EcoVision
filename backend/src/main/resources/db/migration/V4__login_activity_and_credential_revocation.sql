ALTER TABLE users ADD COLUMN IF NOT EXISTS credentials_changed_at timestamptz;
UPDATE users SET longest_login_streak = COALESCE(login_streak_count, 0)
WHERE longest_login_streak IS NULL OR longest_login_streak < COALESCE(login_streak_count, 0);
CREATE TABLE IF NOT EXISTS user_login_days (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    login_date date NOT NULL,
    UNIQUE (user_id, login_date)
);
END
$$;
